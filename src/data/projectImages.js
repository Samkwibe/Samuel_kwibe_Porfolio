export function fallbackProjectImage(project) {
  return projectImageUrls[project.id] || categoryImageUrls[project.category] || defaultProjectImageUrl
}

export function projectImageSource(project, baseUrl = '') {
  if (project.image?.startsWith('http')) {
    return project.image
  }

  const localPath = project.image?.replace(/^\//, '')

  if (localPath && localProjectImagePaths.has(localPath)) {
    return `${baseUrl}${localPath}`
  }

  return fallbackProjectImage(project)
}
